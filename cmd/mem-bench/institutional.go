package main

// InstitutionalBench v1 (spec §17.3) — the internal benchmark for what memba
// is actually for: institutional coding memory. Nothing public tests this.
//
// The generator is deterministic (seeded) and public, per spec; a private,
// hash-pinned split with human-reviewed gold labels layers on top for real
// campaigns (§17.6) — this in-repo corpus is the public sample + regression
// suite. Task families: onboarding Q&A · stale-doc traps · migration
// ordering · ownership lookup · prior-failure avoidance · forbidden-file
// avoidance · command recall · abstention.
//
//	mem-bench institutional --token $TOK [--services 3] [--seed 7]
//	  [--write-corpus corpus.jsonl] [--mode deep] [-v]
//
// Scoring is evidence-level (like the LME adapter): a case passes when the
// pack surfaces the gold marker(s). Stale-doc traps require the CURRENT
// truth (code/CI), not the stale doc's claim. Reported per family against
// the T4 targets (§17.5).

import (
	"context"
	"encoding/json"
	"flag"
	"fmt"
	"math/rand"
	"os"
	"sort"
	"strings"
	"time"

	"github.com/lazorfuzz/memba/pkg/client"
	"github.com/lazorfuzz/memba/pkg/evalapi"
	"github.com/lazorfuzz/memba/pkg/memory"
)

type instCase struct {
	Family   string
	ID       string
	Query    string
	Expected []string // all must appear in the pack (evidence recall)
	Abstain  bool
}

type instService struct {
	name      string
	namespace string
	items     []evalapi.BenchmarkItem
	cases     []instCase
}

// generateService builds one synthetic service corpus + cases. Deterministic
// for a given rng state.
func generateService(rng *rand.Rand, idx int) instService {
	names := []string{"payments-api", "ledger-sync", "invoice-gen", "tax-calc", "refund-svc", "billing-edge"}
	teams := []string{"team:payments", "team:ledger", "team:billing-core"}
	name := fmt.Sprintf("%s-%d", names[rng.Intn(len(names))], idx)
	team := teams[rng.Intn(len(teams))]
	oldCmd := fmt.Sprintf("scripts/deploy_%s.sh", name)
	newCmd := fmt.Sprintf("make release SERVICE=%s", name)
	genFile := "internal/schema/schema_gen.go"
	failSig := fmt.Sprintf("ERROR: fixture reset failed for %s: database locked by stale advisory lock", name)

	svc := instService{name: name, namespace: "/instbench/repos/" + name}
	day := func(d int) *time.Time {
		t := time.Date(2026, 3, 1, 12, 0, 0, 0, time.UTC).AddDate(0, 0, d)
		return &t
	}
	add := func(sourceType, uri, title, body string, eventDay int, meta map[string]any) {
		svc.items = append(svc.items, evalapi.BenchmarkItem{
			NamespaceID: svc.namespace, SourceType: sourceType, SourceURI: uri,
			Title: title, Body: body, EventTime: day(eventDay), Metadata: meta,
		})
	}

	// --- corpus -------------------------------------------------------------
	// Current code: generated file marker + build config.
	add(memory.SourceGit, "git://"+name+"/"+genFile, "",
		"// Code generated by schemagen. DO NOT EDIT.\n// source: schema.yaml — edit that and run `make schema`\npackage schema\n", 1,
		map[string]any{"path": genFile})
	add(memory.SourceGit, "git://"+name+"/Makefile", "",
		fmt.Sprintf("test:\n\tgo test ./...\n\nschema:\n\tschemagen schema.yaml\n\nrelease:\n\t./ci/release.sh $(SERVICE)\n# deploys go through `%s`\n", newCmd), 1,
		map[string]any{"path": "Makefile"})
	add(memory.SourceGit, "git://"+name+"/CODEOWNERS", "",
		"* "+team+"\n/internal/schema/ "+team+"\n", 1, map[string]any{"path": "CODEOWNERS"})

	// STALE doc (older): claims the retired deploy command.
	add(memory.SourceDoc, "doc://"+name+"/runbooks/deploy.md", "Deploying "+name,
		fmt.Sprintf("# Deploying %s\n\nRun `%s` from the ops box.\n(This runbook predates the CI migration.)\n", name, oldCmd), 3, nil)
	// Newer CI evidence: the current truth.
	add(memory.SourceCI, "ci://"+name+"/runs/501", "",
		fmt.Sprintf("release pipeline: `%s` succeeded\nnote: %s was removed in the CI migration; deploys only run via make release\n", newCmd, oldCmd), 20, nil)

	// Migration-ordering runbook.
	add(memory.SourceDoc, "doc://"+name+"/runbooks/schema-migration.md", "Schema migration order",
		"# Adding a schema field safely\n\n1. Edit schema.yaml (never the generated go file).\n2. Run `make schema` to regenerate.\n3. Run `make test`.\n4. Deploy the reader before the writer.\n", 5, nil)

	// Incident postmortem.
	add(memory.SourceIncident, "incident://INC-"+fmt.Sprint(700+idx), "Double-charge incident",
		fmt.Sprintf("INC: %s double-charged invoices when the writer deployed before the reader.\nPrevention: always deploy the reader before the writer.\n", name), 8, nil)

	// Repeated failed agent runs (prior-failure family).
	for r := 0; r < 3; r++ {
		add(memory.SourceAgentRun, fmt.Sprintf("agentrun://%s-run-%d/log", name, r), "",
			fmt.Sprintf("task: refresh test fixtures\nstep 2 ok\n%s\nrun aborted\n", failSig), 10+r,
			map[string]any{"run_outcome": "failed"})
	}

	// --- cases ----------------------------------------------------------------
	svc.cases = []instCase{
		{Family: "command_recall", ID: name + "/cmd-test",
			Query:    "what command runs the tests for " + name + "?",
			Expected: []string{"go test ./..."}},
		{Family: "forbidden_file_avoidance", ID: name + "/forbidden",
			Query:    "can I edit internal/schema/schema_gen.go in " + name + " to add a field?",
			Expected: []string{"DO NOT EDIT"}},
		{Family: "stale_doc_trap", ID: name + "/deploy",
			Query: "how do I deploy " + name + "?",
			// Credit requires the CURRENT truth (CI evidence), not just the
			// stale runbook's claim.
			Expected: []string{newCmd}},
		{Family: "migration_ordering", ID: name + "/migration",
			Query:    "what is the safe order for adding a schema field to " + name + "?",
			Expected: []string{"make schema", "reader before the writer"}},
		{Family: "ownership_lookup", ID: name + "/owner",
			Query:    "which team owns " + name + "?",
			Expected: []string{team}},
		{Family: "prior_failure_avoidance", ID: name + "/prior-failure",
			Query:    "has refreshing test fixtures for " + name + " failed before?",
			Expected: []string{"advisory lock"}},
		{Family: "onboarding", ID: name + "/onboarding",
			Query:    "I'm new to " + name + " — what should I know about the schema files?",
			Expected: []string{"schema.yaml"}},
		{Family: "abstention", ID: name + "/abstain-oncall",
			Query:   "who is on-call for " + name + " this week?",
			Abstain: true},
		{Family: "abstention", ID: name + "/abstain-budget",
			Query:   "what is the cloud spend budget for " + name + " this quarter?",
			Abstain: true},
	}
	return svc
}

// T4 targets (§17.5), checked per family where defined.
var t4Targets = map[string]float64{
	"forbidden_file_avoidance": 90,
	"stale_doc_trap":           85,
	"prior_failure_avoidance":  80,
}

func cmdInstitutional(args []string) {
	fs := flag.NewFlagSet("institutional", flag.ExitOnError)
	base := fs.String("base", "http://localhost:8080", "memd base URL")
	token := fs.String("token", os.Getenv("MEMBA_TOKEN"), "bearer token")
	services := fs.Int("services", 3, "synthetic services to generate")
	seed := fs.Int64("seed", 7, "generator seed (determinism/contamination control)")
	mode := fs.String("mode", memory.ModeDeep, "query mode")
	writeCorpus := fs.String("write-corpus", "", "also dump the generated corpus+cases as JSONL")
	verbose := fs.Bool("v", false, "log per-case results")
	fs.Parse(args)
	if *token == "" {
		fatal("--token required")
	}

	rng := rand.New(rand.NewSource(*seed))
	var svcs []instService
	for i := 0; i < *services; i++ {
		svcs = append(svcs, generateService(rng, i))
	}
	if *writeCorpus != "" {
		if err := dumpCorpus(*writeCorpus, svcs); err != nil {
			fatal("write corpus: %v", err)
		}
		fmt.Printf("corpus written to %s\n", *writeCorpus)
	}

	ctx := context.Background()
	mem := evalapi.NewV1(client.New(*base, *token))
	if err := mem.Client.Healthz(ctx); err != nil {
		fatal("memd not reachable: %v", err)
	}

	type famScore struct{ total, hits, tokens int }
	perFam := map[string]*famScore{}
	failures := 0

	for _, svc := range svcs {
		if err := mem.Reset(ctx, svc.namespace); err != nil {
			fatal("reset %s: %v", svc.namespace, err)
		}
		for _, item := range svc.items {
			if err := mem.Insert(ctx, item); err != nil {
				fatal("insert %s: %v", item.SourceURI, err)
			}
		}
		for _, tc := range svc.cases {
			pack, err := mem.Query(ctx, evalapi.BenchmarkQuery{
				NamespaceID: svc.namespace, Query: tc.Query, Mode: *mode,
			})
			if err != nil {
				failures++
				fmt.Fprintf(os.Stderr, "%s: %v\n", tc.ID, err)
				continue
			}
			hit := scoreInst(tc, pack)
			f := perFam[tc.Family]
			if f == nil {
				f = &famScore{}
				perFam[tc.Family] = f
			}
			f.total++
			f.tokens += pack.TokenTotal
			if hit {
				f.hits++
			}
			if *verbose {
				status := "MISS"
				if hit {
					status = "HIT "
				}
				fmt.Printf("%s %-26s %-32s answerability=%s\n", status, tc.Family, tc.ID, pack.Answerability)
			}
		}
	}

	fmt.Println("\n=== InstitutionalBench v1 (public sample split) ===")
	fmt.Printf("services=%d seed=%d mode=%s\n", *services, *seed, *mode)
	fams := make([]string, 0, len(perFam))
	for f := range perFam {
		fams = append(fams, f)
	}
	sort.Strings(fams)
	t4Failed := false
	for _, fam := range fams {
		f := perFam[fam]
		rate := pct(f.hits, f.total)
		line := fmt.Sprintf("%-26s %3d/%3d (%.1f%%) · avg %d tok", fam, f.hits, f.total, rate, f.tokens/max(f.total, 1))
		if target, ok := t4Targets[fam]; ok {
			mark := "✓"
			if rate < target {
				mark, t4Failed = "✗", true
			}
			line += fmt.Sprintf("   [T4 ≥ %.0f%% %s]", target, mark)
		}
		fmt.Println(line)
	}
	if failures > 0 || t4Failed {
		os.Exit(1)
	}
}

func scoreInst(tc instCase, pack memory.EvidencePack) bool {
	if tc.Abstain {
		return pack.Answerability == "low" || len(pack.MissingEvidence) > 0
	}
	hay := strings.ToLower(packText(pack))
	for _, want := range tc.Expected {
		if !strings.Contains(hay, strings.ToLower(want)) {
			return false
		}
	}
	return len(tc.Expected) > 0
}

func dumpCorpus(path string, svcs []instService) error {
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	defer f.Close()
	enc := json.NewEncoder(f)
	for _, svc := range svcs {
		if err := enc.Encode(map[string]any{"type": "reset", "namespace": svc.namespace}); err != nil {
			return err
		}
		for _, item := range svc.items {
			if err := enc.Encode(map[string]any{"type": "insert", "item": item}); err != nil {
				return err
			}
		}
		for _, tc := range svc.cases {
			if err := enc.Encode(map[string]any{"type": "query", "query": evalapi.BenchmarkQuery{
				NamespaceID: svc.namespace, Query: tc.Query, Expected: tc.Expected,
				Abstain: tc.Abstain, CaseID: tc.ID, CaseFamily: tc.Family,
			}}); err != nil {
				return err
			}
		}
	}
	return nil
}
